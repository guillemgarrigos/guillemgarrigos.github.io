const langButton = document.querySelector('.lang-toggle');
let currentLanguage = Lang.get();

function setLanguage(language, save = true) {
  currentLanguage = language;
  if (save) Lang.set(language);
  const dict = translations[language];
  document.documentElement.lang = language;
  document.title = dict.pageTitle;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const value = dict[el.dataset.i18n];
    if (value !== undefined) el.innerHTML = value;
  });
  document.querySelectorAll('[data-i18n-alt]').forEach(el => {
    const value = dict[el.dataset.i18nAlt];
    if (value !== undefined) el.alt = value;
  });
  if (typeof showStatus === 'function' && formState) showStatus(formState);
  if (langButton) {
    langButton.textContent = language === 'es' ? 'EN' : 'ES';
    langButton.setAttribute('aria-label', dict.langLabel);
  }
}

if (langButton) {
  langButton.addEventListener('click', () => setLanguage(currentLanguage === 'es' ? 'en' : 'es'));
}

/* Mobile menu */
const menuButton = document.querySelector('.menu-toggle');
const nav = document.querySelector('.nav');
if (menuButton && nav) {
  const closeMenu = () => {
    nav.classList.remove('open');
    menuButton.setAttribute('aria-expanded', 'false');
    menuButton.textContent = '☰';
  };
  menuButton.addEventListener('click', () => {
    const open = nav.classList.toggle('open');
    menuButton.setAttribute('aria-expanded', String(open));
    menuButton.textContent = open ? '×' : '☰';
  });
  nav.querySelectorAll('a').forEach(a => a.addEventListener('click', closeMenu));
}

/* Contact form (Web3Forms): sent in the background, status shown under the button */
const form = document.querySelector('.contact-form');
const statusEl = document.querySelector('.form-status');
let formState = '';

function showStatus(state) {
  formState = state;
  if (!statusEl) return;
  const keys = { sending: 'formSending', success: 'formSuccess', error: 'formError', invalid: 'formInvalid' };
  statusEl.hidden = !state;
  statusEl.className = 'form-status' + (state ? ' is-' + state : '');
  statusEl.textContent = state ? translations[currentLanguage][keys[state]] : '';
}

if (form) {
  form.addEventListener('submit', async event => {
    event.preventDefault();
    if (!form.checkValidity()) { showStatus('invalid'); form.reportValidity(); return; }
    const data = Object.fromEntries(new FormData(form).entries());
    if (data.botcheck) return; // honeypot filled in: it is a bot
    const reasonSelect = form.elements.reason;
    data.reason = reasonSelect.options[reasonSelect.selectedIndex].textContent;
    data.subject = 'Portfolio: ' + data.reason;
    data.language = currentLanguage;
    const button = form.querySelector('.submit-button');
    button.disabled = true;
    showStatus('sending');
    try {
      const response = await fetch(form.action, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
        body: JSON.stringify(data)
      });
      const result = await response.json();
      if (!response.ok || !result.success) throw new Error(result.message || 'Request failed');
      form.reset();
      showStatus('success');
    } catch (error) {
      console.error('Contact form error:', error);
      showStatus('error');
    } finally {
      button.disabled = false;
    }
  });
}

setLanguage(currentLanguage, false);
